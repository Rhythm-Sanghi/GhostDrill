import { expect, test } from '@playwright/test'

test('the built drill can be diagnosed, fixed, and reset', async ({ page }) => {
  const pageErrors: string[] = []
  page.on('pageerror', (error) => pageErrors.push(error.message))
  await page.goto('./')

  const run = page.getByRole('region', { name: 'Drill outcome' })
  const map = page.getByRole('region', { name: 'Service map' })
  const evidence = page.getByRole('region', { name: 'Evidence' })
  const proof = evidence.getByRole('region', { name: 'Rollback proof' })
  const printing = proof.getByRole('article', { name: 'Label printing' })
  const endpoint = proof.getByRole('article', { name: 'Queue endpoint' })
  const selected = evidence.getByRole('region', { name: 'Selected snapshot' })
  const timeline = page.getByRole('region', { name: 'Runbook' })
  const launch = page.getByRole('button', { name: 'Try the warehouse drill' })
  const rerun = page.getByRole('button', { name: 'Rerun drill' })

  await expect(launch).toBeInViewport()
  await expect(map.getByText('Can print', { exact: true })).toBeVisible()
  await launch.click()
  await expect(run.getByText('Rollback completed')).toBeVisible()
  await expect(run.getByText('Failed', { exact: true })).toBeVisible()
  await expect(run.getByText('Failed in Rollback')).toBeVisible()
  await expect(run.getByText('Service still down')).toBeVisible()
  await expect(evidence.getByText('Change · Switch queue to backup')).toBeVisible()
  await expect(map.getByText('gw-backup', { exact: true })).toBeVisible()
  await expect(map.getByText('Cannot print', { exact: true })).toBeVisible()
  await expect(printing.getByRole('group', { name: 'Baseline' }).getByText('Healthy')).toBeVisible()
  await expect(printing.getByRole('group', { name: 'Rollback' }).getByText('Unhealthy')).toBeVisible()
  await expect(endpoint.getByRole('group', { name: 'Rollback' }).getByText('The queue targets gw-backup and requires gw-primary.')).toBeVisible()

  await evidence.getByRole('button', { name: 'Inspect responsible step' }).click()
  const switchQueue = timeline.getByRole('button', { name: 'Switch queue to backup' })
  await expect(switchQueue).toBeFocused()
  await expect(switchQueue).toHaveAttribute('aria-current', 'step')
  await expect(map.getByText('Change snapshot')).toBeVisible()
  await expect(map.getByText('Path reachable', { exact: true })).toHaveCount(1)
  await timeline.getByRole('button', { name: 'Take primary offline' }).click()
  await expect(map.getByText('Path reachable', { exact: true })).toHaveCount(0)
  await expect(selected.getByRole('article', { name: 'Label printing' }).getByText('Backup gateway cannot reach the print service.')).toBeVisible()

  await timeline.getByRole('button', { name: 'Restore label queue endpoint' }).click()
  await expect(timeline.getByText('Pending edit · Rerun to apply')).toBeVisible()
  await expect(run.getByText('Showing the previous plan')).toBeVisible()
  await expect(run.getByText('Service still down')).toBeVisible()
  await rerun.click()
  await expect(run.getByText('Service recovered')).toBeVisible()
  await expect(run.getByText('Verified', { exact: true })).toBeVisible()
  await expect(run.getByText('Showing the previous plan')).toHaveCount(0)
  await expect(printing.getByRole('group', { name: 'Rollback' }).getByText('Primary gateway can reach the print service.')).toBeVisible()
  await expect(map.getByText('gw-primary', { exact: true })).toBeVisible()
  await expect(map.getByText('Can print', { exact: true })).toBeVisible()

  await timeline.getByRole('button', { name: 'Capture starting state' }).click()
  await expect(map.getByText('Baseline snapshot')).toBeVisible()
  await expect(evidence.getByText('First outage')).toHaveCount(0)
  await expect(selected.getByRole('article', { name: 'Label printing' }).getByText('Primary gateway can reach the print service.')).toBeVisible()
  await switchQueue.click()
  await expect(selected.getByRole('article', { name: 'Label printing' }).getByText('Backup gateway cannot reach the print service.')).toBeVisible()
  await expect(run.getByText('Service recovered')).toBeVisible()

  await timeline.getByRole('button', { name: 'Remove endpoint restore' }).click()
  await expect(timeline.getByText('Removed from plan')).toBeVisible()
  await rerun.click()
  await expect(run.getByText('Service still down')).toBeVisible()
  await expect(timeline.getByText('Removed from plan')).toHaveCount(0)

  await timeline.getByRole('button', { name: 'Restore label queue endpoint' }).click()
  await rerun.click()
  await expect(run.getByText('Service recovered')).toBeVisible()
  await page.getByRole('button', { name: 'Reset' }).click()
  await expect(launch).toBeFocused()
  await expect(run.getByText('Ready to run')).toBeVisible()
  await expect(map.getByText('Baseline snapshot')).toBeVisible()
  await expect(timeline.getByRole('button', { name: 'Restore label queue endpoint' })).toBeDisabled()
  await launch.click()
  await expect(run.getByText('Service still down')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
  expect(pageErrors).toEqual([])
})

test('missing evidence is repeatable and scenario switching clears past edits and proof', async ({ page }) => {
  await page.goto('./')
  const picker = page.getByRole('combobox', { name: 'Scenario' })
  const outcome = page.getByRole('region', { name: 'Drill outcome' })
  const timeline = page.getByRole('region', { name: 'Runbook' })
  const map = page.getByRole('region', { name: 'Service map' })
  const proof = page.getByRole('region', { name: 'Rollback proof' })
  const launchWarehouse = page.getByRole('button', { name: 'Try the warehouse drill' })
  const launchMissing = page.getByRole('button', { name: 'Try the missing evidence drill' })

  await launchWarehouse.click()
  await timeline.getByRole('button', { name: 'Restore label queue endpoint' }).click()
  await picker.selectOption({ label: 'Missing Print Path Evidence' })
  await expect(outcome.getByText('Awaiting rollback')).toBeVisible()
  await expect(proof).toHaveCount(0)
  await expect(timeline.getByText('Pending edit', { exact: false })).toHaveCount(0)
  await expect(timeline.getByText('Edit rollback')).toHaveCount(0)

  for (let attempt = 0; attempt < 2; attempt++) {
    await launchMissing.click()
    await expect(outcome.getByText('Rollback completed')).toBeVisible()
    await expect(outcome.getByText('Unknown', { exact: true })).toBeVisible()
    const printing = proof.getByRole('article', { name: 'Label printing' })
    const rollback = printing.getByRole('group', { name: 'Rollback' })
    await expect(printing.getByRole('group', { name: 'Baseline' }).getByText('Healthy')).toBeVisible()
    await expect(rollback.getByText('Missing observation: reachability from the primary gateway to the print service.')).toBeVisible()
    await expect(rollback.getByRole('button')).toHaveCount(0)
    await expect(proof.getByRole('article', { name: 'Queue endpoint' }).getByRole('group', { name: 'Rollback' }).getByText('Healthy')).toBeVisible()
    await expect(map.getByText('Path unobserved')).toBeVisible()
    await expect(map.getByText('Print status unknown')).toBeVisible()
    await timeline.getByRole('button', { name: 'Capture starting state' }).click()
    await expect(map.getByText('Can print', { exact: true })).toBeVisible()
    await expect(map.getByText('Path unobserved')).toHaveCount(0)
    await expect(outcome.getByText('Unknown', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Reset' }).click()
    await expect(outcome.getByText('Awaiting rollback')).toBeVisible()
    await expect(launchMissing).toBeFocused()
  }

  await picker.selectOption({ label: 'Warehouse Label Outage' })
  await expect(outcome.getByText('Awaiting rollback')).toBeVisible()
  await expect(launchWarehouse).toBeVisible()
  await launchWarehouse.click()
  await expect(outcome.getByText('Failed', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
})

test('the main flow works using the keyboard', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name === 'mobile', 'Desktop keyboard check')
  await page.goto('./')
  const run = page.getByRole('region', { name: 'Drill outcome' })
  const launch = page.getByRole('button', { name: 'Try the warehouse drill' })
  await page.keyboard.press('Tab')
  await expect(page.getByRole('combobox', { name: 'Scenario' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(launch).toBeFocused()
  await expect(launch).toHaveCSS('outline-style', 'solid')
  await page.keyboard.press('Enter')
  await expect(run.getByText('Service still down')).toBeVisible()
  for (let index = 0; index < 7; index++) await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Inspect responsible step' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('button', { name: 'Switch queue to backup' })).toBeFocused()
  for (let index = 0; index < 3; index++) await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Restore label queue endpoint' })).toBeFocused()
  await page.keyboard.press('Space')
  for (let index = 0; index < 5; index++) await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('button', { name: 'Rerun drill' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(run.getByText('Service recovered')).toBeVisible()
  await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('button', { name: 'Reset' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(launch).toBeFocused()
})
