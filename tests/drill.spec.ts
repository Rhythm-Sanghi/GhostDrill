import { expect, test } from '@playwright/test'

test('the built drill can be diagnosed, fixed, and reset', async ({ page }) => {
  const pageErrors: string[] = []
  page.on('pageerror', (error) => pageErrors.push(error.message))
  await page.goto('./')

  const run = page.getByRole('region', { name: 'Drill outcome' })
  const map = page.getByRole('region', { name: 'Service map' })
  const evidence = page.getByRole('region', { name: 'Evidence' })
  const timeline = page.getByRole('region', { name: 'Runbook' })
  const launch = page.getByRole('button', { name: 'Try the warehouse drill' })
  const rerun = page.getByRole('button', { name: 'Rerun drill' })

  await expect(launch).toBeInViewport()
  await expect(map.getByText('Can print', { exact: true })).toBeVisible()
  await launch.click()
  await expect(run.getByText('Rollback completed')).toBeVisible()
  await expect(run.getByText('Service still down')).toBeVisible()
  await expect(evidence.getByText('Change · Switch queue to backup')).toBeVisible()
  await expect(map.getByText('gw-backup', { exact: true })).toBeVisible()
  await expect(map.getByText('Cannot print', { exact: true })).toBeVisible()

  await evidence.getByRole('button', { name: 'Inspect responsible step' }).click()
  const switchQueue = timeline.getByRole('button', { name: 'Switch queue to backup' })
  await expect(switchQueue).toBeFocused()
  await expect(switchQueue).toHaveAttribute('aria-current', 'step')
  await expect(map.getByText('Change snapshot')).toBeVisible()
  await expect(map.getByText('Path reachable', { exact: true })).toHaveCount(1)
  await timeline.getByRole('button', { name: 'Take primary offline' }).click()
  await expect(map.getByText('Path reachable', { exact: true })).toHaveCount(0)

  await timeline.getByRole('button', { name: 'Restore label queue endpoint' }).click()
  await expect(timeline.getByText('Pending edit · Rerun to apply')).toBeVisible()
  await expect(run.getByText('Service still down')).toBeVisible()
  await rerun.click()
  await expect(run.getByText('Service recovered')).toBeVisible()
  await expect(evidence.getByText('Printing available')).toBeVisible()
  await expect(map.getByText('gw-primary', { exact: true })).toBeVisible()
  await expect(map.getByText('Can print', { exact: true })).toBeVisible()

  await timeline.getByRole('button', { name: 'Capture starting state' }).click()
  await expect(map.getByText('Baseline snapshot')).toBeVisible()
  await expect(evidence.getByText('First outage')).toHaveCount(0)
  await switchQueue.click()
  await expect(evidence.getByText('Printing unavailable')).toBeVisible()
  await expect(run.getByText('Service recovered')).toBeVisible()

  await timeline.getByRole('button', { name: 'Remove endpoint restore' }).click()
  await expect(timeline.getByText('Removed from plan')).toBeVisible()
  await rerun.click()
  await expect(run.getByText('Service still down')).toBeVisible()
  await expect(timeline.getByText('Removed from plan')).toHaveCount(0)

  await timeline.getByRole('button', { name: 'Restore label queue endpoint' }).click()
  await rerun.click()
  await expect(run.getByText('Service recovered')).toBeVisible()
  await page.getByRole('button', { name: 'Reset' }).click()
  await expect(launch).toBeFocused()
  await expect(run.getByText('Ready to run')).toBeVisible()
  await expect(map.getByText('Baseline snapshot')).toBeVisible()
  await expect(timeline.getByRole('button', { name: 'Restore label queue endpoint' })).toBeDisabled()
  await launch.click()
  await expect(run.getByText('Service still down')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
  expect(pageErrors).toEqual([])
})

test('the main flow works using the keyboard', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name === 'mobile', 'Desktop keyboard check')
  await page.goto('./')
  const run = page.getByRole('region', { name: 'Drill outcome' })
  const launch = page.getByRole('button', { name: 'Try the warehouse drill' })
  await page.keyboard.press('Tab')
  await expect(launch).toBeFocused()
  await expect(launch).toHaveCSS('outline-style', 'solid')
  await page.keyboard.press('Enter')
  await expect(run.getByText('Service still down')).toBeVisible()
  for (let index = 0; index < 6; index++) await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Inspect responsible step' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('button', { name: 'Switch queue to backup' })).toBeFocused()
  for (let index = 0; index < 3; index++) await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Restore label queue endpoint' })).toBeFocused()
  await page.keyboard.press('Space')
  for (let index = 0; index < 5; index++) await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('button', { name: 'Rerun drill' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(run.getByText('Service recovered')).toBeVisible()
  await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('button', { name: 'Reset' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(launch).toBeFocused()
})
